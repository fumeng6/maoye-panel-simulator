/**
 * 流派数据 - 流派、变体与武学天赋
 *
 * 说明：
 * - 每个流派变体（如"鸣金虹"）选中后即生效一组武学天赋。
 * - 武学天赋中的部分属性受"需求折算"影响（见 domain/panel.js）。
 */

import { 武库 } from './baseStats.js'
import 数据 from './game/流派.json' with { type: 'json' }
import { 取模板属性 } from './templateStats.js'

/** 词条属性所属的元素（用于"无相吸收"与"本系属攻"识别） */
export const 属性元素 = Object.freeze({
  鸣金: { 最小: '最小鸣金攻击', 最大: '最大鸣金攻击', 穿透: '鸣金穿透' },
  裂石: { 最小: '最小裂石攻击', 最大: '最大裂石攻击', 穿透: '裂石穿透' },
  破竹: { 最小: '最小破竹攻击', 最大: '最大破竹攻击', 穿透: '破竹穿透' },
  牵丝: { 最小: '最小牵丝攻击', 最大: '最大牵丝攻击', 穿透: '牵丝穿透' }
})

/**
 * 流派注册表
 * 结构：流派 -> 变体 -> { 武学天赋, 五维需求, 属性需求, 本系属性 }
 */
export const 流派注册表 = Object.fromEntries(Object.entries(数据.流派).map(([流派, 变体表]) => [
  流派,
  Object.fromEntries(Object.entries(变体表).map(([变体, 配置]) => [变体, {
    ...配置,
    五维需求: { 需求值: 数据.五维需求值, ...配置.五维需求 },
    武学天赋: 取模板属性(数据.天赋总表, 配置.天赋属性, 配置.天赋取值, 配置.天赋覆盖)
  }]))
]))

/** 武学天赋中受"五维需求"折算的属性 */
export const 五维折算属性 = Object.freeze([
  '最小外功攻击',
  '最大外功攻击',
  '会心率',
  '会意率'
])

/** 武学天赋中受"属性需求"折算的属性 */
export const 属性折算属性 = Object.freeze([
  '鸣金穿透',
  '裂石穿透',
  '牵丝穿透',
  '破竹穿透',
  '鸣金伤害加成',
  '裂石伤害加成',
  '牵丝伤害加成',
  '破竹伤害加成'
])

/** 武学天赋中直接生效、不参与折算的属性 */
export const 直接生效属性 = Object.freeze([
  '最小鸣金攻击',
  '最大鸣金攻击',
  '最小裂石攻击',
  '最大裂石攻击',
  '最小牵丝攻击',
  '最大牵丝攻击',
  '最小破竹攻击',
  '最大破竹攻击'
])

/** 全部流派列表（用于下拉） */
export const 流派列表 = Object.freeze(
  Object.entries(流派注册表).map(([流派, 变体表]) => ({
    流派,
    变体: Object.keys(变体表)
  }))
)

/**
 * 流派卡片列表（与培养助手 SCHOOLS 口径一致）
 * key = camelCase，name = 全名（如 鸣金虹）
 */
export const 流派卡片列表 = Object.freeze(
  Object.entries(流派注册表).flatMap(([流派, 变体表]) =>
    Object.keys(变体表).map((变体) => ({
      流派,
      变体,
      全名: `${流派}${变体}`,
      启用: true
    }))
  )
)

/** 判断流派卡片是否命中当前选择 */
export function 是否命中流派卡片(卡片, 流派, 变体) {
  return 卡片.流派 === 流派 && 卡片.变体 === 变体
}

/** 取某流派变体的配置 */
export function 取流派配置(流派, 变体) {
  return 流派注册表?.[流派]?.[变体] || null
}

/** 取武库对某本系属性的加成 */
export function 取武库加成(本系属性) {
  const 元素 = 属性元素[本系属性]
  if (!元素) return {}
  return {
    [元素.最小]: 武库.最小属性攻击,
    [元素.最大]: 武库.最大属性攻击
  }
}
