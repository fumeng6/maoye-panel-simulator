function 去重(list) {
  return Array.from(new Set(list.filter(Boolean)))
}

// ==================== 各槽位词条池 ====================

/**
 * 宫槽（初始词条）- 装备自带的固定词条
 */
export function 取宫槽池(部位) {
  if (武器部位.includes(部位)) {
    return [...积木.外功攻击, ...积木.无相攻击, '敏', '势']
  }
  if (首饰部位.includes(部位)) {
    return [...积木.外功攻击]
  }
  // 头/胸：判定 + 防御
  if (部位 === 装备部位.头 || 部位 === 装备部位.胸) {
    return [...积木.判定, '最大气血', '外功防御']
  }
  // 胫甲/腕甲：判定 + 劲 + 防御
  return [...积木.判定, '劲', '最大气血', '外功防御', '体', '御']
}

/**
 * 商/角/徵/羽 调律词条池（合并调律库 + 转律库 + 稀有库）
 * @param {string} 部位
 * @param {string} 流派
 * @param {string} 变体
 */
export function 取调律池(部位, 流派, 变体) {
  const list = []

  // 1) 调律通用库
  if (武器部位.includes(部位)) {
    list.push(...积木.外功攻击, ...积木.无相攻击, ...积木.判定, ...积木.五维)
  } else if (首饰部位.includes(部位)) {
    list.push(...积木.外功攻击, ...积木.全系属攻, ...积木.判定, ...积木.五维)
  } else {
    list.push(...积木.外功攻击, ...积木.全系属攻, ...积木.判定, ...积木.五维, ...积木.防御)
  }

  // 2) 转律流派专属库
  const 本系 = 本系属攻[流派] || []
  if (武器部位.includes(部位)) {
    list.push(...积木.外功攻击, ...积木.无相攻击, ...本系, '会心率', '会意率', '敏', '劲')
  } else if (首饰部位.includes(部位)) {
    list.push(...积木.外功攻击, ...本系, '会心率', '会意率', '势', '劲')
  } else {
    list.push(...积木.外功攻击, ...本系, '会心率', '会意率', '势', '劲')
    // 破竹流派的防具转律额外含 气血/外防/体/御
    if (流派 === '破竹') {
      list.push(...积木.防御)
    }
  }

  // 3) 稀有词条库（按部位）
  if (武器部位.includes(部位)) {
    const 稀有 = 武器稀有词条[`${流派}_${变体}`]?.[部位]
    if (稀有) list.push(稀有)
  } else if (首饰部位.includes(部位)) {
    list.push('全武学增效')
  } else if (部位 === 装备部位.头 || 部位 === 装备部位.胸) {
    list.push('全奇术增伤')
  } else {
    list.push('对首领单位增伤', '对玩家单位增伤')
  }

  return 去重(list)
}

/**
 * 定音词条池
 * @param {string} 部位
 * @param {string} 流派
 * @param {string} 变体
 */
export function 取定音池(部位, 流派, 变体) {
  if (武器部位.includes(部位) || 首饰部位.includes(部位)) {
    return ['无相穿透', '外功穿透', '外功抗性']
  }
  return 防具定音词条[`${流派}_${变体}`] || []
}

/** 取某词条的值域 [min, max] */
export function 取词条范围(名称) {
  if (词条属性[名称]) return 词条属性[名称].范围
  // 防具定音招式词条
  if (Object.values(防具定音词条).some((arr) => arr.includes(名称))) {
    return 招式定音范围
  }
  return [0, 0]
}

/** 判断词条是否为百分比类型 */
export function 是百分比词条(名称) {
  if (词条属性[名称]) return 词条属性[名称].百分比
  // 防具定音招式词条均为百分比
  if (Object.values(防具定音词条).some((arr) => arr.includes(名称))) return true
  return false
}

/** 取词条满值 */
export function 取词条满值(名称) {
  return 取词条范围(名称)[1]
}

