function 累加(base, source) {
  for (const [key, value] of Object.entries(source)) {
    base[key] = (base[key] || 0) + Number(value || 0)
  }
}

function 构建基础面板() {
  const panel = {}
  累加(panel, 世界成长)
  累加(panel, 蹊跷)
  累加(panel, 叠音)
  累加(panel, 人物天赋)
  累加(panel, 系统基础)
  return panel
}

